#!/usr/bin/env node
/**
 * sync-site.mjs — fan the site identity out of site.config.js.
 *
 * site.config.js is the ONE file an adopter edits for identity. This script
 * regenerates the non-JS surfaces (docs/_config.yml, docs/freestruct.config.yml)
 * from it so the landing and the docs cannot disagree about who they are.
 *
 *   node scripts/sync-site.mjs           # write the derived files
 *   node scripts/sync-site.mjs --check   # fail if they are out of date
 *
 * Zero dependencies.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import site from '../site.config.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const jekyllConfig = `# GENERATED by \`node scripts/sync-site.mjs\` from site.config.js - edit that file.
# Hand edits here are drift and fail \`npm run sync:check\`.

title: ${site.name}
baseurl: ${site.docs.baseurl} # the docs deploy path (GitHub Pages project path)
url: ${site.docs.host}
description: "${site.description.replace(/"/g, '\\"')}"

# Identity the layout renders (docs/_layouts/default.html reads these).
repo: ${site.repo}
brand_accent: ${site.wordmark.accent}
brand_rest: ${site.wordmark.rest}
maker_label: ${site.maker.label}
maker_url: ${site.maker.url}
org_name: ${site.org.name}
org_url: ${site.org.url}
site_url: ${site.url}
docs_url: ${site.docs.url}
theme_key: ${site.theme.themeKey}
scheme_key: ${site.theme.schemeKey}
# The shipped defaults (a first visit, nothing stored). The docs layout sets
# these on <html> so the no-JS first paint is right; a stored choice overrides.
default_theme: ${site.theme.defaultMode}
default_scheme: ${site.theme.defaultScheme}

markdown: kramdown
highlighter: rouge
permalink: :title

exclude: ['README.md', 'Gemfile', 'Gemfile.lock', 'tmp', 'pagefind*']

kramdown:
  syntax_highlighter: rouge
  syntax_highlighter_opts:
    default_lang: plaintext
    css_class: 'highlight'
  toc_levels: [1, 2, 3, 4, 5, 6]
  auto_ids: true
  auto_id_prefix: ''

plugins:
  - jekyll-redirect-from
`;

const freestructConfig = `# GENERATED by \`node scripts/sync-site.mjs\` from site.config.js - edit that file.

site:
  name: ${site.name}
  # ORIGIN ONLY - no path. Page paths carry ${site.docs.baseurl} via basePath below.
  url: ${site.docs.host}
  description: "${site.description.replace(/"/g, '\\"')}"

basePath: ${site.docs.baseurl}
outputDir: _site
linkCheck: true

# Auto BreadcrumbList per page: a trail from the URL tree (site root -> path
# segments -> the page title). The home page ships none. Carried since
# freestruct 1.1.0, so every pinned version in the family has it.
breadcrumb: true

author:
  name: ${site.org.name}
  url: ${site.org.url}

jsonLd:
  - "@type": Person
    name: ${site.author}
    url: ${site.repo}
    jobTitle: ${site.name} maintainer

twitter:
  card: summary_large_image
`;

const robotsTxt = `# GENERATED by \`node scripts/sync-site.mjs\` from site.config.js - edit that file.
# Hand edits here are drift and fail \`npm run sync:check\`.

# crawler policy - all the way open, it's a library site
User-agent: *
Allow: /

Sitemap: ${site.url}/sitemap.xml
`;

const manifest = JSON.stringify(
    {
        name: site.name,
        short_name: site.name,
        description: site.description,
        start_url: '/',
        display: 'standalone',
        background_color: '#10131a',
        theme_color: '#10131a',
        lang: 'en',
        icons: [
            { src: '/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
            { src: '/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
            { src: '/icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' },
        ],
    },
    null,
    2
) + '\n';

const targets = [
    [join(root, 'docs', '_config.yml'), jekyllConfig],
    [join(root, 'docs', 'freestruct.config.yml'), freestructConfig],
    [join(root, 'web', 'public', 'robots.txt'), robotsTxt],
    [join(root, 'web', 'public', 'site.webmanifest'), manifest],
];

let drift = false;
for (const [path, content] of targets) {
    const current = safeRead(path);
    if (current === content) continue;
    if (check) {
        drift = true;
        console.error('drift: ' + path.replace(root + '/', '') + ' is out of date (run `node scripts/sync-site.mjs`)');
    } else {
        writeFileSync(path, content);
        console.log('wrote ' + path.replace(root + '/', ''));
    }
}

if (check && drift) process.exit(1);
if (check) console.log('site surfaces are in sync');
process.exit(0);

function safeRead(path) {
    try { return readFileSync(path, 'utf8'); } catch { return null; }
}
